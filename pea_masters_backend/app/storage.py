"""Where uploaded files' bytes live. A local folder for now (settings.storage_dir); the rest of the app only uses
these functions, so moving to object storage (S3-compatible) on a server means changing this file only."""

import hashlib
import uuid
from pathlib import Path

from app.config import settings


def _root() -> Path:
    root = Path(settings.storage_dir).resolve()
    root.mkdir(parents=True, exist_ok=True)
    return root


def _path(key: str) -> Path:
    path = (_root() / key).resolve()
    if _root() not in path.parents:  # keys are generated by us, but never let one point outside the folder
        raise ValueError("storage key outside storage")
    return path


def save(data: bytes, folder: str, extension: str) -> tuple[str, str]:
    """Stores the bytes under a new random key. Returns (storage key, sha256)."""
    key = f"{folder}/{uuid.uuid4().hex}.{extension}"
    path = _path(key)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return key, hashlib.sha256(data).hexdigest()


def path_of(key: str) -> Path:
    return _path(key)
